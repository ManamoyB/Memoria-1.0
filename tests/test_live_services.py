"""Opt-in real-service tests. Only unique test collections and temporary files are used."""

import os
from uuid import uuid4

import pytest

from app.memory.config import MemorySettings
from app.memory.contracts import SearchRequest
from app.memory.database import Database
from app.memory.runtime import Runtime

pytestmark = pytest.mark.skipif(
    os.getenv("MEMORIA_LIVE_TESTS") != "1",
    reason="Set MEMORIA_LIVE_TESTS=1 for Ollama/Qdrant tests",
)


def test_real_ollama_qdrant_pipeline(tmp_path):
    settings = MemorySettings(
        database_url=f"sqlite:///{tmp_path / 'live.db'}",
        qdrant_collection="memoria_test_" + uuid4().hex,
        provider_timeout=300,
        obsidian_enabled=False,
    )
    database = Database(settings.database_url.get_secret_value())
    database.create_for_tests()
    rt = Runtime(settings, database)
    rt.repo.bootstrap(settings.owner_id)
    try:
        assert rt.llm.health()["available"]
        assert rt.index.health()["available"]
        job = rt.repo.submit(
            settings.owner_id,
            "ingestion",
            {
                "content": "Raja prefers Python for backend development.",
                "source_id": "live-verification-source",
                "source_type": "text",
            },
        )
        result = rt.process(job["id"])
        assert result["status"] in ("COMPLETED", "WAITING_FOR_REVIEW"), result
        assert result["result"]["memories"], "Model extracted no memories from explicit fact"
        for memory in result["result"]["memories"]:
            if memory["status"] == "WAITING_FOR_REVIEW":
                rt.repo.resolve(settings.owner_id, memory["id"], "keep_both")
        assert rt.sync.run(settings.owner_id, force=True)["failed"] == 0
        found = rt.retrieval.search(
            settings.owner_id,
            SearchRequest(query="Which language does Raja prefer?", mode="semantic"),
        )
        assert found["results"]
        assert "Python" in found["results"][0]["memory"]["content"]
    finally:
        # Collection name was generated by this test, never a configured user collection.
        rt.index.request("DELETE", "/collections/" + settings.qdrant_collection)
        rt.close()
